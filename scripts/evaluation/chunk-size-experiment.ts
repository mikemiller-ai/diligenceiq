#!/usr/bin/env -S pnpm exec tsx
/**
 * Chunk-size experiment (Phase 3 decision; SPEC §25.1; architecture §6.2). Free and offline:
 * re-chunks the corpus at several target sizes, builds an in-memory BM25 index for each, and
 * runs the retrieval eval set in BM25-only mode with the same ~24K-token context budget. The
 * context target scales with the chunk size so every size fills the same budget.
 *
 * BM25 only, because embedding another chunking costs ~$0.44 and an hour per size; the
 * result therefore says how lexical retrieval and context packing respond to chunk size,
 * not how the embeddings do. The c2 run re-derives the index version to prove the default
 * sizing still produces iv-9cf51c066743.
 *
 * Gold recall@context is comparable across sizes: the gold labels are c2 chunk IDs, resolved to
 * their filing character spans, and a gold passage counts as retrieved when the context's
 * chunks of that filing cover at least half of it (packages/rag `goldRecall`).
 *
 *   pnpm eval:chunk-size
 *
 * Writes `evals/results/chunk-size-<indexVersion>.json` and `.md`. No AWS.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';
import { type ChunkSizing, DEFAULT_SIZING, chunkFiling, defaultCorpusPath, embeddingText, loadCorpus, processFilings } from '@diligenceiq/corpus';
import { EvalFileSchema, type GoldSpan, Retriever, TARGET_CONTEXT_CHUNKS, TOKENIZER_VERSION, buildBm25, loadBm25, scoreRetrieval, summarize } from '@diligenceiq/rag';
import { ROOT, indexVersionForChunks } from '../lib/common';

const SIZINGS: Array<{ name: string; sizing: ChunkSizing }> = [
  { name: '1,800 chars (~450 tokens)', sizing: { targetChars: 1_800, overlapChars: 240, hardCapChars: 3_000 } },
  { name: '2,700 chars (~675 tokens)', sizing: { targetChars: 2_700, overlapChars: 360, hardCapChars: 4_500 } },
  { name: '3,600 chars (~900 tokens, c2)', sizing: DEFAULT_SIZING },
  { name: '5,400 chars (~1,350 tokens)', sizing: { targetChars: 5_400, overlapChars: 720, hardCapChars: 9_000 } },
];

const file = EvalFileSchema.parse(parse(readFileSync(join(ROOT, 'evals', 'questions.yaml'), 'utf8')));
const corpus = loadCorpus(defaultCorpusPath(ROOT));
const filings = processFilings(corpus.filings);
console.log(`eval:chunk-size ${filings.length} filings × ${SIZINGS.length} sizes, ${file.questions.length} questions, BM25 only`);

const chunkAt = (sizing: ChunkSizing) => filings.flatMap((f) => chunkFiling(f.meta, f.text, f.sections, sizing));
const c2Chunks = chunkAt(DEFAULT_SIZING);
const goldSpans = new Map<string, GoldSpan>(c2Chunks.map((c) => [c.chunkId, c]));

const results: Array<Record<string, unknown>> = [];
for (const { name, sizing } of SIZINGS) {
  const t0 = performance.now();
  const chunks = sizing === DEFAULT_SIZING ? c2Chunks : chunkAt(sizing);
  const { meta, postings } = buildBm25(chunks.map(embeddingText), TOKENIZER_VERSION);
  const version = sizing === DEFAULT_SIZING ? indexVersionForChunks(chunks) : null;
  const retriever = new Retriever({ chunks, bm25: loadBm25(meta, postings), vectors: null, dims: 0 }, version ?? `experiment-${sizing.targetChars}`);
  const targetChunks = Math.round((TARGET_CONTEXT_CHUNKS * DEFAULT_SIZING.targetChars) / sizing.targetChars);
  const scores = [];
  for (const q of file.questions) {
    const r = await retriever.retrieve(q.question, {}, null, { mode: 'bm25', targetChunks });
    scores.push(scoreRetrieval(q, r, (id) => retriever.chunk(id), (id) => goldSpans.get(id)));
  }
  const s = summarize(name, scores);
  const lengths = chunks.map((c) => c.text.length).sort((a, b) => a - b);
  const row = {
    name,
    sizing,
    chunks: chunks.length,
    medianChars: lengths[Math.floor(lengths.length / 2)],
    targetChunks,
    indexVersion: version,
    summary: s,
    failing: scores.filter((x) => !x.pass).map((x) => `${x.id} (${x.checks.filter((c) => !c.pass).map((c) => c.name).join(', ')})`),
    seconds: Math.round((performance.now() - t0) / 100) / 10,
  };
  results.push(row);
  console.log(
    `  ${name}: ${chunks.length} chunks; ${s.passed}/${s.questions} pass, evidence ${s.evidenceHitRate}, gold recall ${s.goldRecall} (${s.goldHits}/${s.goldTotal}), section precision ${s.sectionPrecision}, on-topic ${s.relevantShare}${version ? `; version ${version}` : ''}${row.failing.length ? `; failing ${row.failing.join(', ')}` : ''} (${row.seconds}s)`,
  );
}

const indexVersion = (results.find((r) => r.indexVersion) as { indexVersion: string } | undefined)?.indexVersion ?? 'unknown';
const outDir = join(ROOT, 'evals', 'results');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, `chunk-size-${indexVersion}.json`), `${JSON.stringify({ ranAt: new Date().toISOString(), indexVersion, results }, null, 1)}\n`);
const md = [
  `# Chunk-size experiment — ${indexVersion}`,
  '',
  `Generated by \`pnpm eval:chunk-size\` on ${new Date().toLocaleDateString('en-CA')} (local). BM25 only (no embeddings), same ~24K-token context budget, context target scaled by chunk size. ${file.questions.length} questions from \`evals/questions.yaml\`.`,
  '',
  '| Target | Chunks | Median chars | Context target | Questions passing | Evidence hit rate | Gold recall@context (mean; hits/labeled) | Section precision | On-topic share | Failing |',
  '|---|---|---|---|---|---|---|---|---|---|',
  ...results.map((r) => {
    const s = r.summary as ReturnType<typeof summarize>;
    return `| ${r.name} | ${r.chunks} | ${r.medianChars} | ${r.targetChunks} | ${s.passed}/${s.questions} | ${s.evidenceHitRate} | ${s.goldRecall} (${s.goldHits}/${s.goldTotal}) | ${s.sectionPrecision} | ${s.relevantShare} | ${(r.failing as string[]).join('; ') || '—'} |`;
  }),
  '',
];
writeFileSync(join(outDir, `chunk-size-${indexVersion}.md`), md.join('\n'));
console.log(`  wrote evals/results/chunk-size-${indexVersion}.json and .md`);
